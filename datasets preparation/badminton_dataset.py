"""PyTorch Dataset Module for Badminton Shot Classification (Phase 1 / Phase 2).

Provides the BadmintonShotDataset implementation for reading video clips
from the Phase 1 split manifest. Decodes frames on-the-fly via OpenCV without
caching full videos in memory, samples fixed-length temporal sequences,
and formats tensors for CNN-LSTM architectures.
"""

from __future__ import annotations

import csv
import logging
import os
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple, Union

import numpy as np
import torch
from torch.utils.data import Dataset

try:
    import cv2  # type: ignore
    HAS_CV2 = True
except ImportError:
    HAS_CV2 = False

logger = logging.getLogger("badminton_dataset")

# Canonical class mapping
CANONICAL_CLASSES: List[str] = ["Clear", "Drive", "Drop", "Net_Shot", "Smash"]
CLASS_TO_IDX: Dict[str, int] = {c: i for i, c in enumerate(CANONICAL_CLASSES)}
IDX_TO_CLASS: Dict[int, str] = {i: c for i, c in enumerate(CANONICAL_CLASSES)}


class BadmintonShotDataset(Dataset):
    """PyTorch Dataset for video-based badminton shot classification.

    Parameters:
        manifest_path: Path to split_manifest.csv generated by dataset_split.py.
        split: Split filter: 'train', 'val', 'test', or 'all'.
        num_frames: Number of temporal frames to sample per clip (default 16).
        frame_size: Spatial target resolution (height, width), default (224, 224).
        sampling_strategy: Temporal sampling strategy ('uniform' or 'consecutive').
        transform: Optional transform callable applied to the [T, C, H, W] tensor.
        return_dict: If True, returns dict with metadata; if False, returns (tensor, label).
        on_decode_error: How to handle unreadable video: 'raise' or 'zero'.
        base_dir: Optional base directory to resolve relative clip paths.
    """

    def __init__(
        self,
        manifest_path: str | Path,
        split: str = "train",
        num_frames: int = 16,
        frame_size: Tuple[int, int] = (224, 224),
        sampling_strategy: str = "uniform",
        transform: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
        return_dict: bool = True,
        on_decode_error: str = "raise",
        base_dir: Optional[str | Path] = None,
    ) -> None:
        super().__init__()
        self.manifest_path = Path(manifest_path).resolve()
        self.split = split.lower()
        self.num_frames = num_frames
        self.frame_size = frame_size
        self.sampling_strategy = sampling_strategy
        self.transform = transform
        self.return_dict = return_dict
        self.on_decode_error = on_decode_error
        self.base_dir = Path(base_dir).resolve() if base_dir else self.manifest_path.parent.parent.parent

        if not self.manifest_path.exists():
            raise FileNotFoundError(
                f"Split manifest not found at: {self.manifest_path}. "
                f"Run dataset_split.py to generate split_manifest.csv first."
            )

        if not HAS_CV2:
            raise ImportError("OpenCV (cv2) is required for BadmintonShotDataset video decoding.")

        self.samples: List[Dict[str, Any]] = []
        self._load_manifest()

    def _load_manifest(self) -> None:
        """Reads and filters entries from the split manifest CSV."""
        with open(self.manifest_path, "r", encoding="utf-8") as fp:
            reader = csv.DictReader(fp)
            for row in reader:
                item_split = row.get("split", "").lower()

                # Filter by requested split
                if self.split != "all" and item_split != self.split:
                    continue
                # Never include excluded duplicates in active splits
                if item_split == "excluded" and self.split != "excluded":
                    continue

                raw_path = row["clip_path"]
                resolved_p = self._resolve_path(raw_path)

                class_name = row["canonical_label"]
                class_idx = int(row.get("class_index", CLASS_TO_IDX.get(class_name, -1)))
                if class_idx < 0 and class_name in CLASS_TO_IDX:
                    class_idx = CLASS_TO_IDX[class_name]

                self.samples.append(
                    {
                        "clip_path": str(resolved_p),
                        "filename": row.get("filename", resolved_p.name),
                        "class_name": class_name,
                        "class_index": class_idx,
                        "split": item_split,
                        "source_group": row.get("source_group", ""),
                    }
                )

        if not self.samples:
            logger.warning("No samples loaded for split='%s' from manifest: %s", self.split, self.manifest_path)

    def _resolve_path(self, raw_path: str) -> Path:
        """Resolves clip path against filesystem robustly."""
        p = Path(raw_path)
        if p.is_absolute() and p.exists():
            return p
        # Try relative to base_dir
        candidate = self.base_dir / raw_path
        if candidate.exists():
            return candidate
        # Try relative to manifest directory
        candidate2 = self.manifest_path.parent / raw_path
        if candidate2.exists():
            return candidate2
        return p

    def __len__(self) -> int:
        return len(self.samples)

    def _sample_indices(self, total_frames: int) -> List[int]:
        """Calculates frame indices to sample based on selected strategy."""
        if total_frames <= 0:
            return [0] * self.num_frames

        if total_frames <= self.num_frames:
            # Repeat frames if video has fewer frames than required
            indices = list(range(total_frames))
            while len(indices) < self.num_frames:
                indices.append(indices[-1])
            return indices[: self.num_frames]

        if self.sampling_strategy == "uniform":
            # Uniformly spaced frame sampling across full clip duration
            return np.linspace(0, total_frames - 1, num=self.num_frames, dtype=int).tolist()
        elif self.sampling_strategy == "consecutive":
            # Sample consecutive segment from center
            start = max(0, (total_frames - self.num_frames) // 2)
            return list(range(start, start + self.num_frames))
        else:
            # Fallback uniform
            return np.linspace(0, total_frames - 1, num=self.num_frames, dtype=int).tolist()

    def _decode_video(self, file_path: str) -> torch.Tensor:
        """Decodes sampled video frames into a float32 tensor of shape [T, C, H, W]."""
        p = Path(file_path)
        if not p.exists():
            if self.on_decode_error == "raise":
                raise FileNotFoundError(f"Video file does not exist: {file_path}")
            return torch.zeros((self.num_frames, 3, *self.frame_size), dtype=torch.float32)

        cap = cv2.VideoCapture(file_path)
        if not cap.isOpened():
            if self.on_decode_error == "raise":
                raise IOError(f"Could not open video stream: {file_path}")
            return torch.zeros((self.num_frames, 3, *self.frame_size), dtype=torch.float32)

        total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
        target_indices = set(self._sample_indices(total_frames))
        ordered_indices = self._sample_indices(total_frames)

        # Read frames sequentially for speed and reliability
        frames_dict: Dict[int, np.ndarray] = {}
        frame_idx = 0
        max_target = max(target_indices) if target_indices else 0

        while frame_idx <= max_target:
            ret, frame = cap.read()
            if not ret:
                break
            if frame_idx in target_indices:
                # Resize and convert BGR -> RGB
                h, w = self.frame_size
                resized = cv2.resize(frame, (w, h), interpolation=cv2.INTER_LINEAR)
                rgb = cv2.cvtColor(resized, cv2.COLOR_BGR2RGB)
                frames_dict[frame_idx] = rgb
            frame_idx += 1

        cap.release()

        # Assemble frames in correct order
        assembled: List[np.ndarray] = []
        last_valid = np.zeros((*self.frame_size, 3), dtype=np.uint8)

        for idx in ordered_indices:
            if idx in frames_dict:
                last_valid = frames_dict[idx]
                assembled.append(last_valid)
            else:
                assembled.append(last_valid)

        if not assembled:
            if self.on_decode_error == "raise":
                raise IOError(f"No frames successfully decoded from video: {file_path}")
            return torch.zeros((self.num_frames, 3, *self.frame_size), dtype=torch.float32)

        # Stack to [T, H, W, C] -> Permute to [T, C, H, W] -> Normalize to [0.0, 1.0]
        stacked = np.stack(assembled, axis=0)  # [T, H, W, C]
        tensor = torch.from_numpy(stacked).permute(0, 3, 1, 2).contiguous().float() / 255.0

        return tensor

    def __getitem__(self, idx: int) -> Union[Tuple[torch.Tensor, torch.Tensor], Dict[str, Any]]:
        sample = self.samples[idx]
        file_path = sample["clip_path"]
        class_idx = sample["class_index"]

        # Decode video
        frames_tensor = self._decode_video(file_path)

        # Apply optional transform
        if self.transform is not None:
            frames_tensor = self.transform(frames_tensor)

        label_tensor = torch.tensor(class_idx, dtype=torch.long)

        if self.return_dict:
            return {
                "frames": frames_tensor,
                "label": label_tensor,
                "class_name": sample["class_name"],
                "clip_path": file_path,
                "source_group": sample["source_group"],
                "split": sample["split"],
            }
        else:
            return frames_tensor, label_tensor


def main() -> None:
    """Quick validation inspection for BadmintonShotDataset."""
    import argparse

    parser = argparse.ArgumentParser(description="Test BadmintonShotDataset.")
    parser.add_argument(
        "--manifest",
        type=str,
        default="Phase -1 Data preparation/report/split_manifest.csv",
        help="Path to split_manifest.csv",
    )
    parser.add_argument("--split", type=str, default="train", choices=["train", "val", "test", "all"])
    parser.add_argument("--num_frames", type=int, default=16)

    args = parser.parse_args()

    ds = BadmintonShotDataset(manifest_path=args.manifest, split=args.split, num_frames=args.num_frames)
    print(f"Dataset '{args.split}' loaded with {len(ds)} samples.")

    if len(ds) > 0:
        item = ds[0]
        frames = item["frames"]
        label = item["label"]
        print(f"Sample 0: path={item['clip_path']}")
        print(f"  Frames shape: {frames.shape} (dtype={frames.dtype}, min={frames.min():.2f}, max={frames.max():.2f})")
        print(f"  Label: {label.item()} ({item['class_name']})")


if __name__ == "__main__":
    main()
