import sys
from pathlib import Path
from tempfile import NamedTemporaryFile
from uuid import uuid4

# Resolve models/ml_model_rudra so src.predict and src.model import cleanly
PROJECT_ROOT = Path(__file__).resolve().parent.parent
RUDRA_DIR = PROJECT_ROOT / "models" / "ml_model_rudra"
if str(RUDRA_DIR) not in sys.path:
    sys.path.insert(0, str(RUDRA_DIR))
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from starlette.concurrency import run_in_threadpool

from src.predict import predict_video


app = FastAPI(
    title="Badminton Shot Recognition API",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

ALLOWED_EXTENSIONS = {".mp4", ".avi", ".mov", ".mkv"}
MAX_FILE_SIZE = 100 * 1024 * 1024


@app.get("/")
def home():
    return {"status": "running", "docs": "/docs"}


@app.get("/api/health")
def health():
    return {"status": "healthy"}


@app.post("/predict")
async def predict(file: UploadFile = File(...)):
    filename = Path(file.filename or "").name
    extension = Path(filename).suffix.lower()

    if extension not in ALLOWED_EXTENSIONS:
        raise HTTPException(
            status_code=400,
            detail="Upload an MP4, AVI, MOV, or MKV video.",
        )

    content = await file.read(MAX_FILE_SIZE + 1)

    if not content:
        raise HTTPException(
            status_code=400,
            detail="Uploaded video is empty.",
        )

    if len(content) > MAX_FILE_SIZE:
        raise HTTPException(
            status_code=413,
            detail="Video exceeds 100 MB.",
        )

    temp_path = None

    try:
        # Save the uploaded video temporarily so OpenCV can read it.
        with NamedTemporaryFile(
            suffix=extension,
            delete=False,
        ) as temp_file:
            temp_file.write(content)
            temp_path = Path(temp_file.name)

        # Run actual trained-model inference.
        result = await run_in_threadpool(
            predict_video,
            temp_path,
        )

        predicted_class = result["predicted_class"]
        confidence = float(result["confidence"])
        probabilities = result["probabilities"]

        return {
            "success": True,
            "request_id": str(uuid4()),
            "filename": filename,
            "prediction": predicted_class,
            "predicted_class": predicted_class,
            "class_name": predicted_class,
            "predicted_label": predicted_class,
            "label": predicted_class,
            "confidence": confidence,
            "confidence_score": confidence,
            "probabilities": probabilities,
            "message": "Prediction generated by the trained model.",
        }

    except FileNotFoundError as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Required file not found: {exc}",
        ) from exc

    except ValueError as exc:
        raise HTTPException(
            status_code=400,
            detail=str(exc),
        ) from exc

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Model inference failed: {exc}",
        ) from exc

    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("backend.main:app", host="127.0.0.1", port=8000, reload=True)
